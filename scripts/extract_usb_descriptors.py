#!/usr/bin/env python3
"""Extract the verified USB descriptor regions from the reference firmware."""

from __future__ import annotations

import argparse
from pathlib import Path


REGIONS = (
    ("usb_device_descriptor", 0x036C, 18),
    ("usb_configuration_descriptor", 0x037E, 116),
    ("usb_report_descriptor_0", 0x03F2, 18),
    ("usb_report_descriptor_1", 0x0404, 21),
    ("usb_report_descriptor_2", 0x0419, 220),
    ("usb_report_descriptor_3", 0x04F5, 28),
    ("usb_string_language", 0x0511, 4),
    ("usb_string_manufacturer", 0x0515, 14),
    ("usb_string_product", 0x0525, 56),
)


def format_array(name: str, data: bytes, offset: int) -> str:
    lines = [
        f"/* Reference flash 0x{offset:04x}, {len(data)} bytes. */",
        f"const uint8_t {name}[] PROGMEM = {{",
    ]
    for index in range(0, len(data), 12):
        chunk = ", ".join(f"0x{value:02x}" for value in data[index : index + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    image = args.binary.read_bytes()
    sections = [
        "/* Generated by scripts/extract_usb_descriptors.py. */",
        '#include "usb_descriptors.h"',
        "",
        "#include <avr/pgmspace.h>",
        "",
    ]
    for name, offset, length in REGIONS:
        data = image[offset : offset + length]
        if len(data) != length:
            raise ValueError(f"{name} extends beyond the firmware image")
        sections.extend((format_array(name, data, offset), ""))

    args.output.write_text("\n".join(sections))


if __name__ == "__main__":
    main()
